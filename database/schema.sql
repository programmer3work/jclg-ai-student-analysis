CREATE TABLE IF NOT EXISTS jclg_stream (
    stream_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stream_code VARCHAR(20) NOT NULL UNIQUE,
    stream_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS jclg_group (
    group_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_code VARCHAR(20) NOT NULL UNIQUE,
    group_name VARCHAR(100) NOT NULL,
    stream_id INTEGER NOT NULL REFERENCES jclg_stream(stream_id)
);

